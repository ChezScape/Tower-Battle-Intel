function normaliseReportLabel(value = "") {
    return String(value)
        .toLowerCase()
        .replace(/&/g, " and ")
        .replace(/[\/]+/g, " ")
        .replace(/[^a-z0-9]+/g, " ")
        .replace(/\s+/g, " ")
        .trim();
}

const FIELD_BY_PROPERTY = new Map(SCHEMA.fields.map((field) => [field.property, field]));
const FIELD_BY_KEY = new Map(SCHEMA.fields.map((field) => [field.key, field]));
const ALIASES_BY_KEY = new Map();

for (const alias of SCHEMA.aliases) {
    if (!alias.aliasKey || !alias.property) continue;
    if (!ALIASES_BY_KEY.has(alias.aliasKey)) ALIASES_BY_KEY.set(alias.aliasKey, []);
    ALIASES_BY_KEY.get(alias.aliasKey).push(alias);
}

function findOfficialBattleReportField(labelOrProperty = "") {
    const raw = String(labelOrProperty || "").trim();
    if (!raw) return null;

    if (FIELD_BY_PROPERTY.has(raw)) return FIELD_BY_PROPERTY.get(raw);
    if (FIELD_BY_KEY.has(raw)) return FIELD_BY_KEY.get(raw);

    const normalised = normaliseReportLabel(raw);
    const matches = ALIASES_BY_KEY.get(normalised) || [];
    if (!matches.length) return null;

    const property = matches[0].property;
    return FIELD_BY_PROPERTY.get(property) || null;
}

function getOfficialBattleReportAliases(labelOrProperty = "") {
    const field = findOfficialBattleReportField(labelOrProperty);
    if (!field) return [];
    return SCHEMA.aliases.filter((alias) => alias.property === field.property);
}

function getOfficialBattleReportFamily(labelOrProperty = "") {
    const field = findOfficialBattleReportField(labelOrProperty);
    return field ? field.family : null;
}

function getOfficialBattleReportSection(labelOrProperty = "") {
    const field = findOfficialBattleReportField(labelOrProperty);
    return field ? field.section : null;
}

function explainOfficialBattleReportField(labelOrProperty = "") {
    const field = findOfficialBattleReportField(labelOrProperty);
    if (!field) {
        return {
            ok: false,
            input: labelOrProperty,
            message: "No official/observed v28.1.0 Battle Report field match found."
        };
    }

    return {
        ok: true,
        input: labelOrProperty,
        property: field.property,
        key: field.key,
        displayLabel: field.displayLabel,
        family: field.family,
        section: field.section,
        meaning: field.meaning,
        sourceConfidence: field.sourceConfidence,
        aliases: getOfficialBattleReportAliases(field.property).map((alias) => alias.alias)
    };
}

function auditParsedReportLabels(labels = []) {
    const known = [];
    const unknown = [];

    for (const label of labels || []) {
        const field = findOfficialBattleReportField(label);
        if (field) {
            known.push({ input: label, property: field.property, displayLabel: field.displayLabel, family: field.family, section: field.section });
        } else {
            unknown.push(String(label));
        }
    }

    return {
        ok: unknown.length === 0,
        total: (labels || []).length,
        knownCount: known.length,
        unknownCount: unknown.length,
        known,
        unknown
    };
}

function getOfficialBattleReportSchemaStatus() {
    const fieldCount = SCHEMA.fields.length;
    const aliasCount = SCHEMA.aliases.filter((alias) => alias.property).length;
    const sectionCount = SCHEMA.sections.length;
    const otherKills = explainOfficialBattleReportField("Other");
    const otherCoins = explainOfficialBattleReportField("Other Coin Bonuses");

    return {
        ok: fieldCount >= 140 && aliasCount >= 200 && Boolean(otherKills.ok) && Boolean(otherCoins.ok),
        version: SCHEMA.manifest.recommendedTbiBuild,
        gameVersion: SCHEMA.manifest.version,
        fieldCount,
        aliasCount,
        sectionCount,
        checks: {
            otherKillsMapsTo: otherKills.property || null,
            otherCoinBonusesMapsTo: otherCoins.property || null,
            hitDestroyedEffectRulePresent: true
        },
        warning: "This schema is for labels/fields/grouping only. It does not prove hidden formulas."
    };
}

